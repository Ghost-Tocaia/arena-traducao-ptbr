"""Decoder for Arena's IMG compression "type 8": an adaptive Huffman coder
combined with an LZ77-style back-reference scheme (structurally the classic
"LZHUF" family). Ported from OpenTESArena's Compression::decodeType08.

Only decoding is implemented (no encoder) since there's no need to ever
write type 8 - a translated file can always be saved back out as type 4
(LZSS, see lzss_codec.py) instead, which the game reads just as well.

IMPORTANT calling convention (verified against OpenTESArena's IMGFile.cpp):
a type-8 .IMG's 12-byte header is followed by a 2-byte "decompressed
length" field (little-endian, equal to width*height) BEFORE the actual
Huffman-coded stream starts. That 2 bytes is included in the header's
`length` field but is NOT part of what decode_type08 should read - callers
must pass src = header_end + 2, srcend = header_end + length:

    xoff, yoff, width, height, flags, length = struct.unpack_from("<HHHHHH", data, 0)
    pixels = decode_type08(data, 12 + 2, 12 + length, width * height)

Passing src = 12 (forgetting the +2) desyncs the bitstream immediately -
the decoder still runs without error but produces garbage after the
first few rows, since the adaptive Huffman tree state drifts based on
every bit consumed from the wrong starting point.
"""

