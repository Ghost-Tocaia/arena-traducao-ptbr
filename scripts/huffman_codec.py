def decode_type08(data: bytes, src: int, srcend: int, outlen: int) -> bytes:
    history = bytearray([0x20]) * 4096
    historypos = 0

    node_idx_map = [0] * 941
    for i in range(626):
        node_idx_map[i] = (i >> 1) + 314
    node_idx_map[626] = 0
    for i in range(627, 941):
        node_idx_map[i] = i - 627

    node_tree = [0] * 627
    for i in range(314):
        node_tree[i] = 627 + i
    for i in range(314, 627):
        node_tree[i] = (i - 314) * 2

    node_freq = [0] * 627
    for i in range(314):
        node_freq[i] = 1
    it = 0
    for i in range(314, 627):
        node_freq[i] = node_freq[it] + node_freq[it + 1]
        it += 2

    bitmask = 0
    validbits = 0
    i = src

    dst = bytearray()
    while len(dst) < outlen:
        node = node_tree[626]
        while node < 627:
            while validbits < 9:
                if i < srcend:
                    bitmask |= data[i] << (8 - validbits)
                    i += 1
                bitmask &= 0xFFFF
                validbits += 8
            node = node_tree[node + ((bitmask >> 15) & 1)]
            bitmask = (bitmask << 1) & 0xFFFF
            validbits -= 1

        freqidx = node_idx_map[node]
        while True:
            node_freq[freqidx] += 1
            freq = node_freq[freqidx]
            nextidx = freqidx + 1
            if nextidx < len(node_freq) and node_freq[nextidx] < freq:
                while nextidx < len(node_freq) and node_freq[nextidx] < freq:
                    nextidx += 1
                nextidx -= 1

                node_freq[freqidx] = node_freq[nextidx]
                node_freq[nextidx] = freq

                node_tree[freqidx], node_tree[nextidx] = node_tree[nextidx], node_tree[freqidx]

                mapidx = node_tree[nextidx]
                node_idx_map[mapidx] = nextidx
                if mapidx < 627:
                    node_idx_map[mapidx + 1] = nextidx

                mapidx = node_tree[freqidx]
                node_idx_map[mapidx] = freqidx
                if mapidx < 627:
                    node_idx_map[mapidx + 1] = freqidx

                freqidx = nextidx
            freqidx = node_idx_map[freqidx]
            if freqidx == 0:
                break

        codeword = node - 627
        if codeword < 256:
            b = codeword & 0xFF
            history[historypos & 0xFFF] = b
            historypos += 1
            dst.append(b)
        else:
            while validbits < 9:
                if i < srcend:
                    bitmask |= data[i] << (8 - validbits)
                    i += 1
                bitmask &= 0xFFFF
                validbits += 8
            tableidx = (bitmask >> 8) & 0xFF
            bitmask = (bitmask << 8) & 0xFFFF
            validbits -= 8

            offset_high = HIGH_OFFSET_BITS[tableidx] << 6
            bitcount = LOW_OFFSET_BIT_COUNT[tableidx] - 2
            offset_low = tableidx
            for _ in range(bitcount):
                while validbits < 9:
                    if i < srcend:
                        bitmask |= data[i] << (8 - validbits)
                        i += 1
                    bitmask &= 0xFFFF
                    validbits += 8
                offset_low = ((offset_low << 1) | ((bitmask >> 15) & 1)) & 0xFFFF
                bitmask = (bitmask << 1) & 0xFFFF
                validbits -= 1

            copypos = (historypos - (offset_high | (offset_low & 0x3F)) - 1) & 0xFFFFFFFF
            tocopy = codeword - 256 + 3
            for _ in range(tocopy):
                b = history[copypos & 0xFFF]
                copypos += 1
                history[historypos & 0xFFF] = b
                historypos += 1
                dst.append(b)

    return bytes(dst[:outlen])
